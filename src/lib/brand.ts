/**
 * Everything about how the shop looks when it is NOT a page: the logo files, the tab icon, the
 * home-screen icon, the app names and colours. One file, so the day the official logo arrives
 * (issue #73) the swap is:
 *
 *   1. replace `public/assets/logo.svg` (and `public/assets/favicon.svg`, the simplified mark for 16 to 32 px)
 *   2. `npm run icons`  (regenerates every PNG and favicon.ico under `public/` from those two files)
 *
 * and nothing in `src/` changes. Where each file is used, so nothing is forgotten:
 *
 *   logo.svg                  the header and footer mark (`components/logo.tsx`), the staff header,
 *                             schema.org `logo` (`lib/structured-data.ts`), and the source of every
 *                             generated PNG below
 *   favicon.svg               the tab icon in browsers that take SVG, and the source of the 16 to 48 px PNGs
 *   favicon.ico, favicon-32.png  the tab icon everywhere else. Safari ignores an SVG tab icon, and
 *                             browsers (and Vercel's project list) ask for /favicon.ico by default
 *   apple-touch-icon.png      the iPhone/iPad home-screen tile for the public site
 *   staff-apple-touch-icon.png  the same for the staff app, on the cream page colour (the public one is on
 *                             the emblem's blue, so the two still differ on a home screen)
 *   icon-192 / icon-512 / *-maskable  the web app manifest icons (Android, Chrome, Edge)
 *   og-image.jpg              the link preview (a photo, not the logo; see `OG_IMAGE` in `lib/site.ts`)
 *
 * Outside this repo: the Vercel project's avatar is taken from the deployed /favicon.ico, so it
 * follows the next production deploy by itself. The Instagram and WhatsApp profile pictures are
 * uploaded by hand in those apps and are the one place a logo swap is not automatic.
 *
 * This module is pure data on purpose: the unit tests import it to check that every file named
 * here exists and that each manifest is internally consistent.
 */

