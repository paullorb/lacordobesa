type App = (typeof APPS)[keyof typeof APPS];

/** The manifest JSON for one app, in the shape `MetadataRoute.Manifest` and a route handler both accept. */
export function webManifest(app: App) {
  return {
    id: app.id,
    name: app.name,
    short_name: app.shortName,
    description: app.description,
    start_url: app.startUrl,
    scope: app.scope,
    display: "standalone" as const,
    background_color: app.backgroundColor,
    theme_color: app.themeColor,
    lang: app.lang,
    icons: app.icons.map((icon) => ({ ...icon })),
  };
}
